// Writes src/generated/migrations.ts: the migrations this build knows. Web and worker refuse to start when the
// database's applied migrations differ (another version's images against this database).
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = readdirSync(join(root, "prisma", "migrations"), { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(
  join(root, "src", "generated", "migrations.ts"),
  `// Generated by scripts/known-migrations.mjs from prisma/migrations. Do not edit.\nexport const KNOWN_MIGRATIONS: readonly string[] = ${JSON.stringify(names, null, 2)};\n`,
);
