#!/usr/bin/env node
// Clean-room check: fails if any tracked or untracked (not ignored) text file, file path or commit
// contains a denied term. Nothing about the terms is committed: hashes of short words can be reversed, so the
// hash list stays outside the repo too, in scripts/cleanroom-hashes.local.txt (git-ignored) or, in CI, the
// CLEANROOM_HASHES secret. The plain list stays local in cleanroom-words.local.txt (git-ignored). Never prints
// a term. With no list at all the check fails, unless CLEANROOM_OPTIONAL=1 (pull requests from forks, which get
// no secrets), where it says it skipped.
// Terms may have up to MAX_PARTS segments (split on ".", "-", "_"); --update-hashes refuses longer ones.
// Files over MAX_FILE_BYTES or with a NUL byte are checked by path only and listed as not content-scanned.
//
//   node scripts/cleanroom-check.mjs                  check files, paths and commit metadata
//   node scripts/cleanroom-check.mjs --history        also check full patches of every commit
//   node scripts/cleanroom-check.mjs --update-hashes  rebuild the local hash list from the local word list
//   node scripts/cleanroom-check.mjs --self-test      check the matcher against fake terms in a temp dir
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
const WORDS_FILE = "scripts/cleanroom-words.local.txt";
const HASH_FILE = "scripts/cleanroom-hashes.local.txt";
const MAX_PARTS = 6;
const JOINERS = [".", "-", "_"];
const MAX_FILE_BYTES = 5 * 1024 * 1024;

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
// NFKC folds full-width and compatibility forms (e.g. "－" -> "-", "ａ" -> "a"); the dash and dot look-alikes
// it leaves alone become plain separators too, so no variant of a joiner splits a term in two.
const DASHES = /[\u2010-\u2015\u2043\u2212\u2E3A\u2E3B\uFE58\uFE63\uFF0D]/gu;
const DOTS = /[\u00B7\u2022\u2024\u2027\u2219\u22C5\u3002\u30FB\uFF0E\uFF61\uFF65]/gu;
const fold = (text) => text.normalize("NFKC").replace(DASHES, "-").replace(DOTS, ".");
const normalize = (text) => fold(text).toLowerCase();
const git = (args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 30 });

function updateHashes(wordsPath = join(ROOT, WORDS_FILE), hashPath = join(ROOT, HASH_FILE)) {
  if (!existsSync(wordsPath)) fail(`${WORDS_FILE} not found`);
  const hashes = new Set();
  for (const raw of readFileSync(wordsPath, "utf8").split(/\r?\n/)) {
    const term = normalize(raw.trim());
    if (!term || term.startsWith("#")) continue;
    // Also hash separator variants so "a-b" catches "a.b", "a_b" and "ab".
    const parts = term.split(/[.\-_]/);
    if (parts.length > MAX_PARTS) fail(`a term in ${WORDS_FILE} has ${parts.length} segments; at most ${MAX_PARTS} are matched`);
    for (const variant of [term, ...JOINERS.map((j) => parts.join(j)), parts.join("")]) hashes.add(sha256(variant));
  }
  const header = "# SHA-256 of denied terms (lowercase). Generated by: node scripts/cleanroom-check.mjs --update-hashes\n";
  writeFileSync(hashPath, header + [...hashes].sort().join("\n") + "\n");
  return hashes.size;
}

/** The hash list from `CLEANROOM_HASHES` (CI secret) when `fromEnv`, else from `hashPath`. */
function loadHashes(hashPath, fromEnv = false) {
  const env = fromEnv ? process.env.CLEANROOM_HASHES : undefined;
  if (!env && !existsSync(hashPath)) fail(`${HASH_FILE} not found and CLEANROOM_HASHES not set; run with --update-hashes first`);
  const text = env ?? readFileSync(hashPath, "utf8");
  const hashes = new Set(text.split(/\s+/).filter((l) => /^[0-9a-f]{64}$/.test(l)));
  // An empty list would let everything through without a word.
  if (!hashes.size) fail(`${HASH_FILE} has no hashes; run with --update-hashes`);
  return hashes;
}

/** Single tokens, camelCase parts, and runs of up to MAX_PARTS tokens joined by one of JOINERS. */
function* candidates(raw) {
  const line = fold(raw); // keeps case for the camelCase split
  const tokens = [...line.matchAll(/[\p{L}\p{N}]+/gu)];
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i][0];
    for (const part of token.split(/(?<=[\p{Ll}\p{N}])(?=\p{Lu})/u)) yield normalize(part);
    let run = normalize(token);
    yield run;
    for (let j = i + 1; j < tokens.length && j < i + MAX_PARTS; j++) {
      const prev = tokens[j - 1];
      const sep = line.slice(prev.index + prev[0].length, tokens[j].index);
      if (!JOINERS.includes(sep)) break;
      run += sep + normalize(tokens[j][0]);
      yield run;
    }
  }
}

function matchingLines(text, denied) {
  const lines = [];
  text.split(/\r?\n/).forEach((line, index) => {
    for (const candidate of candidates(line)) {
      if (denied.has(sha256(candidate))) {
        lines.push(index + 1);
        return;
      }
    }
  });
  return lines;
}

/** Checks each path, and the content of text files up to MAX_FILE_BYTES; the rest are returned as not content-scanned. */
function scanFiles(root, files, denied, report) {
  const unscanned = [];
  for (const file of new Set(files)) {
    if (file === HASH_FILE) continue;
    if (matchingLines(file, denied).length) report(`${file} (file path)`);
    const abs = join(root, file);
    if (!existsSync(abs)) continue;
    if (statSync(abs).size > MAX_FILE_BYTES) {
      unscanned.push(`${file} (over ${MAX_FILE_BYTES / 1024 / 1024} MB)`);
      continue;
    }
    const buf = readFileSync(abs);
    if (buf.subarray(0, 8000).includes(0)) {
      unscanned.push(`${file} (binary)`);
      continue;
    }
    for (const line of matchingLines(buf.toString("utf8"), denied)) report(`${file}:${line}`);
  }
  return unscanned;
}

function check(withHistory) {
  if (process.env.CLEANROOM_OPTIONAL === "1" && !process.env.CLEANROOM_HASHES && !existsSync(join(ROOT, HASH_FILE))) {
    console.log("Clean-room check skipped: no term list here (pull requests from forks get no secrets).");
    return;
  }
  const denied = loadHashes(join(ROOT, HASH_FILE), true);
  const findings = [];
  const report = (where) => findings.push(`${where}: matched a denied term`);

  const files = git(["ls-files", "-z", "--cached", "--others", "--exclude-standard"]).split("\0").filter(Boolean);
  const unscanned = scanFiles(ROOT, files, denied, report);

  const hasCommits = (() => {
    try {
      git(["rev-parse", "--verify", "--quiet", "HEAD"]);
      return true;
    } catch {
      return false;
    }
  })();
  if (hasCommits) {
    const scan = (args, label) => {
      for (const record of git(["log", "--all", ...args]).split("\0").filter(Boolean)) {
        const [hash, ...rest] = record.split("\n");
        for (const line of matchingLines(rest.join("\n"), denied)) report(`commit ${hash.slice(0, 12)} ${label} line ${line}`);
      }
    };
    scan(["--format=%x00%H%n%an%n%ae%n%cn%n%ce%n%s%n%b"], "(author/message)");
    if (withHistory) scan(["-p", "--format=%x00%H"], "(patch)");
  }

  if (findings.length) {
    console.log(findings.join("\n"));
    console.error(`\nClean-room check failed: ${findings.length} finding(s).`);
    process.exit(1);
  }
  if (unscanned.length) console.log(`Not content-scanned (path checked only):\n  ${unscanned.join("\n  ")}`);
  console.log(
    `Clean-room check passed (${files.length} files${unscanned.length ? `, ${unscanned.length} by path only` : ""}${hasCommits ? ", commit metadata" : ""}${withHistory && hasCommits ? ", full history" : ""}).`,
  );
}

class CheckError extends Error {}

/** Setup problems (missing or empty lists, a term too long): exit 2 from the entry point. */
function fail(message) {
  throw new CheckError(message);
}

/** Runs `fn` and returns the CheckError message it failed with, or undefined. */
function failure(fn) {
  try {
    fn();
  } catch (err) {
    if (err instanceof CheckError) return err.message;
    throw err;
  }
}

/** Fake terms only: the real list must never appear in output or in the repo. */
function selfTest() {
  const dir = mkdtempSync(join(tmpdir(), "cleanroom-selftest-"));
  try {
    writeFileSync(join(dir, "words.txt"), "# fake\nzorblax-quuxwidget\nfrobnicator\nalfa.brav-char_delt-ecko-foxt\n");
    updateHashes(join(dir, "words.txt"), join(dir, "hashes.txt"));
    const denied = loadHashes(join(dir, "hashes.txt"));
    const caught = [
      "zorblax-quuxwidget",
      "zorblax\uFF0Dquuxwidget", // full-width hyphen-minus
      "zorblax\u2010quuxwidget", // hyphen
      "zorblax\u2212quuxwidget", // minus sign
      "zorblax\uFF0Equuxwidget", // full-width full stop
      "zorblax\u30FBquuxwidget", // katakana middle dot
      "zorblax\u00B7quuxwidget", // middle dot
      "\uFF3AORBLAX_QUUXWIDGET", // full-width letter, upper case
      "zorblaxQuuxwidget",
      "zorblaxquuxwidget",
      "\uFF46\uFF52\uFF4F\uFF42\uFF4E\uFF49\uFF43\uFF41\uFF54\uFF4F\uFF52 b", // full-width letters
      "alfa-brav-char-delt-ecko-foxt", // six segments
      "alfa.brav.char.delt.ecko.foxt",
    ];
    const missed = caught.filter((text) => matchingLines(`x ${text} y`, denied).length === 0);
    const clean = ["zorblax quux widget", "zorblax-quux", "frobnicate", "alfa-brav-char-delt-ecko"].filter((text) => matchingLines(text, denied).length !== 0);
    if (missed.length || clean.length) fail(`self-test failed: missed ${JSON.stringify(missed)}, false hits ${JSON.stringify(clean)}`);

    // Setup mistakes fail loudly instead of passing everything.
    writeFileSync(join(dir, "empty.txt"), "# no hashes\n");
    writeFileSync(join(dir, "long.txt"), "a-b-c-d-e-f-g\n");
    const setup = {
      "empty hash list": failure(() => loadHashes(join(dir, "empty.txt"))),
      "missing hash list": failure(() => loadHashes(join(dir, "missing.txt"))),
      "term over the segment limit": failure(() => updateHashes(join(dir, "long.txt"), join(dir, "long-hashes.txt"))),
    };
    const accepted = Object.keys(setup).filter((k) => setup[k] === undefined);
    if (accepted.length) fail(`self-test failed: accepted ${JSON.stringify(accepted)}`);

    // Oversized and binary files: the path is still checked, the content is reported as not scanned.
    writeFileSync(join(dir, "frobnicator.bin"), Buffer.from([0x7a, 0x00, 0x01]));
    writeFileSync(join(dir, "big.txt"), "x".repeat(MAX_FILE_BYTES + 1));
    writeFileSync(join(dir, "ok.txt"), "nothing to see\n");
    const found = [];
    const unscanned = scanFiles(dir, ["frobnicator.bin", "big.txt", "ok.txt"], denied, (where) => found.push(where));
    const want = ["frobnicator.bin (binary)", `big.txt (over ${MAX_FILE_BYTES / 1024 / 1024} MB)`];
    if (JSON.stringify(found) !== JSON.stringify(["frobnicator.bin (file path)"]) || JSON.stringify(unscanned) !== JSON.stringify(want)) {
      fail(`self-test failed: file scan reported ${JSON.stringify(found)}, not content-scanned ${JSON.stringify(unscanned)}`);
    }
    console.log(`Clean-room self-test passed (${caught.length} variants caught, ${Object.keys(setup).length} setup errors, unscanned files listed).`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const args = new Set(process.argv.slice(2));
try {
  if (args.has("--update-hashes")) console.log(`Wrote ${updateHashes()} hashes to ${HASH_FILE}.`);
  else if (args.has("--self-test")) selfTest();
  else check(args.has("--history"));
} catch (err) {
  if (!(err instanceof CheckError)) throw err;
  console.error(`cleanroom-check: ${err.message}`);
  process.exit(2);
}
